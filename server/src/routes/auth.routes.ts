import { Router } from 'express';
import * as c from '../controllers/auth.controller';
import { requireAuth } from '../middleware/auth';
import { authLimiter } from '../middleware/rateLimit';
import { validate } from '../middleware/validate';
import { asyncHandler } from '../utils/http';
import * as v from '../validators/auth.validators';

const r = Router();
r.get('/csrf', asyncHandler(c.csrf));
r.post('/register', authLimiter, validate({ body: v.registerSchema }), asyncHandler(c.register));
r.post('/login', authLimiter, validate({ body: v.loginSchema }), asyncHandler(c.login));
r.post('/refresh', asyncHandler(c.refresh));
r.post('/logout', asyncHandler(c.logout));
r.get('/me', requireAuth, asyncHandler(c.me));
r.post('/forgot-password', authLimiter, validate({ body: v.forgotSchema }), asyncHandler(c.forgotPassword));
r.post('/reset-password', authLimiter, validate({ body: v.resetSchema }), asyncHandler(c.resetPassword));
r.post('/verify-email', authLimiter, validate({ body: v.verifyEmailSchema }), asyncHandler(c.verifyEmail));
r.post('/resend-verification', requireAuth, authLimiter, asyncHandler(c.resendVerification));
r.post('/change-password', requireAuth, authLimiter, validate({ body: v.changePasswordSchema }), asyncHandler(c.changePassword));
export default r;
